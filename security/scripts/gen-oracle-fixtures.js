#!/usr/bin/env node
/**
 * SCRUM-521-AUDIT-SCOPE — generate `contracts/audit/OracleHeaderFixtures.sol`, the real
 * Bitcoin headers the oracle fuzz harness (`contracts/audit/OracleInvariantHarness.sol`)
 * submits.
 *
 *   node security/scripts/gen-oracle-fixtures.js            # (re)write the contract
 *   node security/scripts/gen-oracle-fixtures.js --check    # exit 1 if it is stale
 *
 * The worlds (canonical chain + one real orphan each) are defined once in
 * `test/utils/oracleHarnessWorlds.js`. `test/audit/OracleInvariantHarness.test.js`
 * re-checks the deployed contract against the JSON fixtures field by field, so a
 * hand edit or a stale regeneration fails CI.
 *
 * Encoding: one 112-byte entry per header, big-endian, in contract field order
 *   prevBlockHash (32) | merkleRootHash (32) | blockHash (32) |
 *   version (4) | timestamp (4) | nBits (4) | nonce (4)
 * Entries 0..count-1 are the canonical chain in height order; entry `count` is the orphan.
 * `blockNumber` is not stored: it is `firstHeight + index` (orphan: `firstHeight + orphanIndex`).
 */

const fs = require("fs");
const path = require("path");
const { loadWorlds } = require("../../test/utils/oracleHarnessWorlds.js");

const OUT = path.join(__dirname, "..", "..", "contracts", "audit", "OracleHeaderFixtures.sol");

const hex32 = (h) => {
  const s = String(h).toLowerCase().replace(/^0x/, "");
  if (!/^[0-9a-f]{64}$/.test(s)) throw new Error(`not a bytes32: ${h}`);
  return s;
};
const hex4 = (n) => {
  if (!Number.isInteger(n) || n < 0 || n > 0xffffffff) throw new Error(`not a uint32: ${n}`);
  return n.toString(16).padStart(8, "0");
};
const entry = (h) =>
  hex32(h.prevBlockHash) + hex32(h.merkleRootHash) + hex32(h.blockHash) + hex4(h.version) + hex4(h.timestamp) + hex4(h.nBits) + hex4(h.nonce);

function worldBlock(w, i) {
  const lines = [];
  lines.push(`    // World ${i}: ${w.name}`);
  for (const src of w.sources) lines.push(`    //   source: ${src}`);
  lines.push(`    uint256 internal constant W${i}_FIRST_HEIGHT = ${w.firstHeight};`);
  lines.push(`    uint256 internal constant W${i}_COUNT = ${w.canonical.length};`);
  lines.push(`    uint256 internal constant W${i}_ORPHAN_INDEX = ${w.orphanIndex}; // orphan height ${w.orphan.blockNumber}`);
  lines.push(`    bytes internal constant W${i}_HEADERS =`);
  w.canonical.forEach((h, j) => {
    if (h.blockNumber !== w.firstHeight + j) throw new Error(`world ${i}: gap at index ${j}`);
    lines.push(`        // [${j}] ${h.blockNumber}`);
    lines.push(`        hex"${entry(h)}"`);
  });
  lines.push(`        // [${w.canonical.length}] ${w.orphan.blockNumber} ORPHAN (sibling of [${w.orphanIndex}])`);
  lines.push(`        hex"${entry(w.orphan)}";`);
  return lines.join("\n");
}

function render(worlds) {
  const infoBranches = worlds
    .map((_, i) => `        if (w == ${i}) return (W${i}_HEADERS, W${i}_FIRST_HEIGHT, W${i}_COUNT, W${i}_ORPHAN_INDEX);`)
    .join("\n");
  return `// SPDX-License-Identifier: AGPL-3.0
pragma solidity 0.8.20;

// =============================================================================
// AUTO-GENERATED by security/scripts/gen-oracle-fixtures.js — DO NOT EDIT BY HAND.
// Regenerate: node security/scripts/gen-oracle-fixtures.js
// World definitions: test/utils/oracleHarnessWorlds.js
// =============================================================================

import {LibDoefinStorage} from "../libraries/LibDoefinStorage.sol";

/**
 * @title OracleHeaderFixtures
 * @notice TEST-ONLY. Real Bitcoin block headers (canonical chains plus real orphans) for
 *         the block-header oracle fuzz harness (\`OracleInvariantHarness\`). SCRUM-521-AUDIT-SCOPE.
 * @dev Deployed by the harness constructor so the ~10 KB of header data lives outside the
 *      harness runtime. Each world is \`count\` canonical headers in height order followed by
 *      one orphan that is a sibling of canonical index \`orphanIndex\`. Every header has
 *      been double-SHA256-, link-, PoW- and median-time-checked against the JSON fixtures
 *      (test/audit/OracleInvariantHarness.test.js re-checks the deployed bytes).
 *      Entry layout (112 bytes, big-endian): prevBlockHash | merkleRootHash | blockHash |
 *      version | timestamp | nBits | nonce.
 */
contract OracleHeaderFixtures {
    error UnknownWorld(uint256 world);
    error FixtureIndexOutOfRange(uint256 world, uint256 index);

    uint256 public constant WORLD_COUNT = ${worlds.length};
    uint256 internal constant ENTRY_SIZE = 112;

${worlds.map(worldBlock).join("\n\n")}

    /// @notice Fixture metadata of world \`w\`.
    /// @return firstHeight Height of canonical index 0.
    /// @return count Number of canonical headers.
    /// @return orphanIndex Canonical index the orphan is a sibling of.
    function info(uint256 w) external pure returns (uint256 firstHeight, uint256 count, uint256 orphanIndex) {
        (, firstHeight, count, orphanIndex) = _world(w);
    }

    /// @notice Header \`i\` of world \`w\`; \`i == count\` is the orphan. \`blockNumber\` is its real height.
    function header(uint256 w, uint256 i) external pure returns (LibDoefinStorage.BlockHeader memory) {
        (bytes memory blob, uint256 first, uint256 count, uint256 orphanIndex) = _world(w);
        if (i > count) revert FixtureIndexOutOfRange(w, i);
        return _decode(blob, i, first + (i == count ? orphanIndex : i));
    }

    /// @notice Canonical headers \`start .. start + len - 1\` of world \`w\`.
    function slice(uint256 w, uint256 start, uint256 len) external pure returns (LibDoefinStorage.BlockHeader[] memory out) {
        (bytes memory blob, uint256 first, uint256 count, ) = _world(w);
        if (start > count || len > count - start) revert FixtureIndexOutOfRange(w, start + len);
        out = new LibDoefinStorage.BlockHeader[](len);
        for (uint256 j = 0; j < len; ++j) {
            out[j] = _decode(blob, start + j, first + start + j);
        }
    }

    /// @notice The orphan branch \`canonical[start .. orphanIndex - 1] ++ [orphan]\` of world \`w\`.
    function orphanBranch(uint256 w, uint256 start) external pure returns (LibDoefinStorage.BlockHeader[] memory out) {
        (bytes memory blob, uint256 first, uint256 count, uint256 orphanIndex) = _world(w);
        if (start > orphanIndex) revert FixtureIndexOutOfRange(w, start);
        uint256 len = orphanIndex - start + 1;
        out = new LibDoefinStorage.BlockHeader[](len);
        for (uint256 j = 0; j + 1 < len; ++j) {
            out[j] = _decode(blob, start + j, first + start + j);
        }
        out[len - 1] = _decode(blob, count, first + orphanIndex);
    }

    /// @notice All block hashes of world \`w\`: canonical in height order, then the orphan.
    function hashes(uint256 w) external pure returns (bytes32[] memory out) {
        (bytes memory blob, , uint256 count, ) = _world(w);
        out = new bytes32[](count + 1);
        for (uint256 i = 0; i <= count; ++i) {
            out[i] = _hashAt(blob, i);
        }
    }

    /// @notice Block hash of header \`i\` of world \`w\` (\`i == count\` is the orphan).
    function hashOf(uint256 w, uint256 i) external pure returns (bytes32) {
        (bytes memory blob, , uint256 count, ) = _world(w);
        if (i > count) revert FixtureIndexOutOfRange(w, i);
        return _hashAt(blob, i);
    }

    function _world(uint256 w) private pure returns (bytes memory, uint256, uint256, uint256) {
${infoBranches}
        revert UnknownWorld(w);
    }

    function _hashAt(bytes memory blob, uint256 entry) private pure returns (bytes32 h) {
        uint256 off = entry * ENTRY_SIZE;
        assembly ("memory-safe") {
            h := mload(add(add(add(blob, 0x20), off), 0x40))
        }
    }

    function _decode(bytes memory blob, uint256 entry, uint256 height) private pure returns (LibDoefinStorage.BlockHeader memory h) {
        uint256 off = entry * ENTRY_SIZE;
        bytes32 prev;
        bytes32 merkle;
        bytes32 hash;
        uint256 tail; // bytes 80..112 of the entry: low half of blockHash, then the four uint32 fields
        assembly ("memory-safe") {
            let p := add(add(blob, 0x20), off)
            prev := mload(p)
            merkle := mload(add(p, 0x20))
            hash := mload(add(p, 0x40))
            tail := mload(add(p, 0x50))
        }
        h.prevBlockHash = prev;
        h.merkleRootHash = merkle;
        h.blockHash = hash;
        h.blockNumber = height;
        h.version = uint32(tail >> 96);
        h.timestamp = uint32(tail >> 64);
        h.nBits = uint32(tail >> 32);
        h.nonce = uint32(tail);
    }
}
`;
}

function main() {
  const source = render(loadWorlds());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== source) {
      console.error(`${path.relative(process.cwd(), OUT)} is stale — run: node security/scripts/gen-oracle-fixtures.js`);
      process.exit(1);
    }
    console.log(`${path.relative(process.cwd(), OUT)} is up to date`);
    return;
  }
  fs.writeFileSync(OUT, source);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}

if (require.main === module) main();

module.exports = { render, OUT };
